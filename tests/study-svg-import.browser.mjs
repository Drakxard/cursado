import test from 'node:test'
import assert from 'node:assert/strict'
import { build } from 'esbuild'
import { chromium } from '@playwright/test'
import { mkdir, readFile } from 'node:fs/promises'

const bundle = await build({ entryPoints: ['lib/study-svg-import.ts'], bundle: true, write: false, format: 'iife', globalName: 'svgImport' })

test('study SVG preserves embedded raster images and blocks active or external content', async t => {
  const browser = await chromium.launch(); t.after(() => browser.close())
  const page = await browser.newPage()
  await page.addScriptTag({ content: bundle.outputFiles[0].text })
  const requests = []
  page.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()) })
  const result = await page.evaluate(async () => {
    const raster = document.createElement('canvas'); raster.width = raster.height = 8
    const ctx = raster.getContext('2d'); ctx.fillStyle = '#ff0000'; ctx.fillRect(0, 0, 8, 8)
    const samples = []
    for (const mime of ['image/png', 'image/jpeg', 'image/webp', 'image/gif']) {
      // A valid single-pixel GIF; the other formats are generated by the browser.
      const data = mime === 'image/gif' ? 'data:image/gif;base64,R0lGODlhAQABAIAAAP8AAAAAACH5BAAAAAAALAAAAAABAAEAAAICRAEAOw==' : raster.toDataURL(mime)
      for (const attribute of ['href', 'xlink:href']) {
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 60 860"><script>window.svgExecuted=true</script><image width="60" height="400" ${attribute}="${data}" onload="window.svgExecuted=true"/><image y="430" width="60" height="400" ${attribute}="${data}"/><image href="https://example.invalid/remote.png" width="60" height="860"/><image href="data:image/svg+xml;base64,PHN2Zy8+"/></svg>`
        const blob = await svgImport.svgToPng(new File([svg], 'fixture.svg'))
        const image = await createImageBitmap(blob)
        const canvas = document.createElement('canvas'); canvas.width = image.width; canvas.height = image.height
        canvas.getContext('2d').drawImage(image, 0, 0); image.close()
        const pixel = y => [...canvas.getContext('2d').getImageData(Math.floor(canvas.width / 2), Math.floor(canvas.height * y), 1, 1).data]
        samples.push({ mime, attribute, width: canvas.width, height: canvas.height, top: pixel(.2), bottom: pixel(.7), gap: pixel(.48) })
        document.body.append(canvas)
      }
    }
    return { samples, executed: Boolean(window.svgExecuted) }
  })
  await mkdir('test-results/study-svg', { recursive: true })
  await page.screenshot({ path: 'test-results/study-svg/embedded-images.png', fullPage: true })
  for (const sample of result.samples) {
    assert.ok(Math.abs(sample.width / sample.height - 60 / 860) < .001)
    for (const pixel of [sample.top, sample.bottom]) {
      assert.ok(pixel[0] > 240 && pixel[1] < 20 && pixel[2] < 20 && pixel[3] === 255, JSON.stringify(sample))
    }
    assert.equal(sample.gap[3], 0)
  }
  assert.equal(result.executed, false)
  assert.deepEqual(requests, [])
})

test('study SVG validates the supplied local example', { skip: !process.env.STUDY_SVG_SAMPLE }, async t => {
  const browser = await chromium.launch(); t.after(() => browser.close())
  const page = await browser.newPage(); await page.addScriptTag({ content: bundle.outputFiles[0].text })
  const source = await readFile(process.env.STUDY_SVG_SAMPLE, 'utf8')
  const result = await page.evaluate(async source => {
    const blob = await svgImport.svgToPng(new File([source], 'sample.svg'))
    const image = await createImageBitmap(blob), canvas = document.createElement('canvas')
    canvas.width = image.width; canvas.height = image.height
    const ctx = canvas.getContext('2d'); ctx.drawImage(image, 0, 0); image.close()
    const pixels = ctx.getImageData(0, 0, canvas.width, canvas.height).data
    let nonWhite = 0
    for (let i = 0; i < pixels.length; i += 4) if (pixels[i + 3] && Math.min(pixels[i], pixels[i + 1], pixels[i + 2]) < 220) nonWhite++
    document.body.append(canvas)
    return { width: canvas.width, height: canvas.height, nonWhite }
  }, source)
  assert.ok(result.nonWhite > 1000, JSON.stringify(result))
  assert.ok(Math.abs(result.width / result.height - 595.302 / 8562.88) < .001)
  await mkdir('test-results/study-svg', { recursive: true })
  await page.screenshot({ path: 'test-results/study-svg/local-example.png', fullPage: true })
})
