async function openLocal(page) {
  await page.route('**/api/**',route=>route.fulfill({status:503,body:'offline'}))
  await page.goto('/pizarra/')
  await page.getByRole('button',{name:'Abrir privadas y copias de este dispositivo'}).click()
}
async function shapes(page) {
  return page.evaluate(async()=>{
    const db=await new Promise(resolve=>{const r=indexedDB.open('pizarra-dispositivo',1);r.onsuccess=()=>resolve(r.result)})
    return new Promise(resolve=>{const r=db.transaction('boards').objectStore('boards').getAll();r.onsuccess=()=>{const board=r.result.find(b=>b.id===localStorage.getItem('pizarra_activa'));db.close();resolve(board?.content?.shapes??[])}})
  })
}
async function matrixMode(page,name) {
  await page.getByRole('button',{name:'MENU · Elegir modo',exact:true}).click()
  await page.locator('.study-menu').getByRole('button',{name:new RegExp(`^${name} `)}).click()
}

