import { build } from 'esbuild'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const entry = new URL('../lib/client/pdf-explanation-graph-player.mjs', import.meta.url)
const output = new URL('../lib/pdf-explanation-graph-player.ts', import.meta.url)

export async function graphRuntimeModule() {
  const require = createRequire(import.meta.url)
  const license = await readFile(join(dirname(require.resolve('d3')), '../LICENSE'), 'utf8')
  const result = await build({
    entryPoints: [fileURLToPath(entry)],
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'iife',
    target: 'es2022',
    minify: true,
    legalComments: 'inline',
  })
  // Also safe inside an inline script: no accidental HTML closing tags.
  const runtime = ('/* D3.js (bundled selection, timer, easing and interpolation)\n' + license.replace(/\r\n/g, '\n') + '\n*/\n' + result.outputFiles[0].text).replace(/<\/script/gi, '<\\/script')
  return '// Generated by scripts/build-pdf-explanation-graph-runtime.mjs; edit lib/client/pdf-explanation-graph-player.mjs.\n' +
    'export const GRAPH_RUNTIME = ' + JSON.stringify(runtime) + '\n'
}

export async function buildGraphRuntime() {
  const require = createRequire(import.meta.url)
  const directory = dirname(require.resolve('katex/dist/katex.min.css'))
  const mathFonts = new Map(await Promise.all((await readdir(join(directory, 'fonts'))).filter(name => name.endsWith('.woff2')).map(async name =>
    [`fonts/${name}`, (await readFile(join(directory, 'fonts', name))).toString('base64')]
  )))
  const css = (await readFile(join(directory, 'katex.min.css'), 'utf8')).replace(/src:[^;}]+/g, declaration => {
    const font = declaration.match(/url\(([^)]+\.woff2)\)/)?.[1]
    return font ? `src:url(data:font/woff2;base64,${mathFonts.get(font)}) format('woff2')` : declaration
  })
  await writeFile(new URL('../lib/pdf-explanation-math-styles.ts', import.meta.url),
    '// Generated by scripts/build-pdf-explanation-graph-runtime.mjs.\nexport const GRAPH_MATH_STYLES = ' + JSON.stringify(css) + '\n', 'utf8')
  await writeFile(output, await graphRuntimeModule(), 'utf8')
}
